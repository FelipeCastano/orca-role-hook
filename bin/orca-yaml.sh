#!/usr/bin/env bash
# Registers the kit as a project's setup script without committing anything (the roles-yaml command).
# Creates orca.yaml at the main checkout's root, ignores it in .git/info/exclude (local, .gitignore is not touched) and lists it
# in .worktreeinclude, also ignored: Orca copies the ignored files listed there to every new worktree,
# before looking for its setup script, so orca.yaml reaches the worktree and Orca runs launch.sh.
# Usage (from any folder in the project):  roles-yaml [--mode <mode>]   |   roles-yaml --remove
#   roles-yaml --mode <mode>   # every new worktree of the project starts in that mode (launch.sh --mode <mode>); rerun to change or drop it
#   roles-yaml --check         # only says whether new worktrees will start the kit (used by roles)
#   roles-yaml --all [--mode <mode>] [--under <dir>] [--dry-run]   # every project registered in Orca at this moment (from anywhere); run --dry-run first
#     without --mode it only registers the projects that have no kit orca.yaml yet and leaves the others and their mode as they are;
#     with --mode <mode> every project is registered or updated to that mode; --under limits it to the projects inside <dir>
# A single-project run ends with a last line ROLES_YAML_RESULT=created|updated|unchanged|skipped:<reason>|error:<reason>
set -euo pipefail
MARK="# Generated by orca-roles (roles-yaml)"
ACTION=add; MODE=""; HAS_MODE=0; ALL=0; DRY=0; UNDER=""; HAS_UNDER=0; RESULT_ON=0
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) sed -n 2,12p "$0"; exit 0;;
    --remove|--check) [ "$ACTION" = add ] || { echo "ERROR: --remove and --check cannot be combined. Usage: roles-yaml [--mode <mode>] | --remove | --check | --all [--mode <mode>] [--under <dir>] [--dry-run]" >&2; exit 1; }; ACTION="${1#--}";;
    --all) ALL=1;;
    --dry-run) DRY=1;;
    --under) HAS_UNDER=1; UNDER="${2:-}"; if [ $# -ge 2 ]; then shift; else shift $#; fi;;
    --mode) HAS_MODE=1; MODE="${2:-}"; if [ $# -ge 2 ]; then shift; else shift $#; fi;;
    *) echo "Unknown option: $1" >&2; exit 1;;
  esac
  [ $# -eq 0 ] || shift
done
[ "$ALL" = 1 ] || [ "$HAS_UNDER" = 0 ] || { echo "ERROR: --under only goes with --all. Usage: roles-yaml --all [--mode <mode>] [--under <dir>] [--dry-run]" >&2; exit 1; }
[ "$ACTION" = add ] || [ "$DRY" = 0 ] || { echo "ERROR: --dry-run only goes with the setup itself (roles-yaml [--mode <mode>] --dry-run, or --all --dry-run); it cannot be combined with --$ACTION." >&2; exit 1; }
[ "$ALL" = 0 ] || [ "$ACTION" = add ] || { echo "ERROR: --all cannot be combined with --$ACTION. Usage: roles-yaml --all [--mode <mode>] [--under <dir>] [--dry-run]" >&2; exit 1; }
[ "$HAS_MODE" = 0 ] || [ "$ACTION" = add ] || { echo "ERROR: --mode only goes with the setup itself: roles-yaml [--mode <mode>]; it cannot be combined with --$ACTION." >&2; exit 1; }
if [ "$ACTION" = add ]; then KIT="${KIT:-$(cd "$(dirname "$0")/.." && pwd)}"; . "$KIT/bin/lib.sh"; fi
if [ "$HAS_MODE" = 1 ]; then
  MODE_ERR="$(mode_error "$MODE")"
  [ -z "$MODE_ERR" ] || { echo "ERROR: --mode: $MODE_ERR. Nothing was written." >&2; [ "$ALL" = 1 ] || echo "ROLES_YAML_RESULT=error:invalid-mode"; exit 1; }
fi
LAUNCH="\$HOME/.orca-roles/bin/launch.sh"; [ -z "$MODE" ] || LAUNCH="$LAUNCH --mode $MODE"

# Single-project add: the last stdout line is ROLES_YAML_RESULT=<value> (the exit trap covers failures nobody handled)
if [ "$ACTION" = add ] && [ "$ALL" = 0 ]; then RESULT_ON=1; fi
finish() { RESULT_ON=0; echo "ROLES_YAML_RESULT=$1"; exit "$2"; }
trap '[ "$RESULT_ON" = 1 ] && echo "ROLES_YAML_RESULT=error:unexpected"' EXIT

orca_cli() {
  if type -P orca >/dev/null 2>&1; then orca "$@"
  elif [ -n "${ORCA_CLI_COMMAND:-}" ] && command -v "$ORCA_CLI_COMMAND" >/dev/null 2>&1; then "$ORCA_CLI_COMMAND" "$@"
  else return 127; fi
}

# roles-yaml --all: registers the kit in every project of "orca repo list" by running this same script in each project's root
if [ "$ALL" = 1 ]; then
  SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
  UNDER_R=""
  if [ "$HAS_UNDER" = 1 ]; then
    [ -n "$UNDER" ] && [ -d "$UNDER" ] || { echo "ERROR: --under: '$UNDER' is not a folder. Usage: roles-yaml --all [--mode <mode>] [--under <dir>] [--dry-run]" >&2; exit 1; }
    UNDER_R="$(cd "$UNDER" && pwd -P)"
  fi
  command -v jq >/dev/null 2>&1 || { echo "ERROR: jq not found: roles-yaml --all needs it to read the project list." >&2; exit 2; }
  LIST_JSON="$(orca_cli repo list --json 2>/dev/null)" || { echo "ERROR: could not read the project list ('orca repo list --json' failed: is Orca running?)." >&2; exit 2; }
  LIST="$(jq -r '.result.repos[] | [(.displayName // ""), .path] | join("\u001f")' <<<"$LIST_JSON" 2>/dev/null)" || { echo "ERROR: unexpected response from 'orca repo list --json'." >&2; exit 2; }
  N_CREATED=0; N_UPDATED=0; N_UNCHANGED=0; N_SKIPPED=0; N_ERRORS=0; SEEN=""
  if [ -n "$MODE" ]; then SET_TXT="mode $MODE"; else SET_TXT="the default mode"; fi
  while IFS=$'\037' read -r NAME RPATH; do
    [ -n "$RPATH" ] || continue
    WINPATH=0; case "$RPATH" in [A-Za-z]:\\*) WINPATH=1;; esac
    if [ "$WINPATH" = 1 ] && [ -z "$NAME" ]; then NAME="$RPATH"; while [ "${NAME%\\}" != "$NAME" ]; do NAME="${NAME%\\}"; done; NAME="${NAME##*\\}"; fi
    RPATH="$(local_path "$RPATH")"
    [ -n "$NAME" ] || NAME="$(basename "$RPATH")"
    if [ -d "$RPATH" ]; then PHYS="$(cd "$RPATH" && pwd -P)"; else PHYS="$RPATH"; fi
    if [ -n "$UNDER_R" ]; then
      case "$PHYS" in "$UNDER_R"|"$UNDER_R"/*) ;; *) continue;; esac
    fi
    LINE=""; WARNS=""
    if [ "$WINPATH" = 1 ]; then LINE="skipped: windows-path (the kit runs in WSL; move the project into WSL)"
    elif [ ! -d "$RPATH" ]; then LINE="skipped: path-missing"
    elif ! git -C "$PHYS" rev-parse --git-dir >/dev/null 2>&1; then LINE="skipped: not-a-repo"
    else
      TOP="$(git -C "$PHYS" rev-parse --show-toplevel 2>/dev/null)" || TOP=""
      CD="$(cd "$PHYS" && cd "$(git rev-parse --git-common-dir 2>/dev/null)" 2>/dev/null && pwd -P)" || CD=""
      if [ -z "$TOP" ] || [ "$(cd "$TOP" && pwd -P)" != "$PHYS" ] || [ "$CD" != "$PHYS/.git" ]; then LINE="skipped: not-main-checkout"
      else
        case "$SEEN" in *"|$CD|"*) LINE="skipped: already-listed";; esac
        SEEN="$SEEN|$CD|"
      fi
    fi
    if [ -z "$LINE" ]; then
      Y="$PHYS/orca.yaml"
      if [ -z "$MODE" ] && [ -f "$Y" ] && grep -qxF "$MARK" "$Y" && ! git -C "$PHYS" ls-files --error-unmatch -- orca.yaml >/dev/null 2>&1; then
        KEPT="$(sed -n 's/^ *\$HOME\/\.orca-roles\/bin\/launch\.sh --mode \([^ ]*\) *$/\1/p' "$Y" | head -n 1)"
        if [ -n "$KEPT" ]; then KEPT_TXT="mode $KEPT kept"; else KEPT_TXT="default mode kept"; fi
        if git -C "$PHYS" check-ignore -q orca.yaml 2>/dev/null && grep -qxF orca.yaml "$PHYS/.worktreeinclude" 2>/dev/null; then
          LINE="unchanged ($KEPT_TXT)"
        elif [ "$DRY" = 1 ]; then
          LINE="would repair ($KEPT_TXT)"
        else
          ARGS=(); [ -z "$KEPT" ] || ARGS+=(--mode "$KEPT")
          ERRF="$(mktemp)"
          OUT="$(cd "$PHYS" && bash "$SELF" ${ARGS[@]+"${ARGS[@]}"} 2>"$ERRF" </dev/null)" || true
          WARNS="$(grep -E '^(WARNING|ERROR):' "$ERRF" || true)"; rm -f "$ERRF"
          RES="$(printf '%s\n' "$OUT" | sed -n 's/^ROLES_YAML_RESULT=//p' | tail -n 1)"
          case "$RES" in
            created|updated|unchanged) LINE="repaired ($KEPT_TXT)";;
            skipped:*) LINE="skipped: ${RES#skipped:}";;
            error:*) LINE="error: ${RES#error:}";;
            *) LINE="error: no-result";;
          esac
        fi
      else
        ARGS=(); [ -z "$MODE" ] || ARGS+=(--mode "$MODE"); [ "$DRY" = 0 ] || ARGS+=(--dry-run)
        ERRF="$(mktemp)"
        OUT="$(cd "$PHYS" && bash "$SELF" ${ARGS[@]+"${ARGS[@]}"} 2>"$ERRF" </dev/null)" || true
        WARNS="$(grep -E '^(WARNING|ERROR):' "$ERRF" || true)"; rm -f "$ERRF"
        RES="$(printf '%s\n' "$OUT" | sed -n 's/^ROLES_YAML_RESULT=//p' | tail -n 1)"
        case "$RES" in
          created) if [ "$DRY" = 1 ]; then LINE="would create"; else LINE="created"; fi;;
          updated) if [ "$DRY" = 1 ]; then LINE="would update to $SET_TXT"; else LINE="updated to $SET_TXT"; fi;;
          unchanged) LINE="unchanged";;
          skipped:*) LINE="skipped: ${RES#skipped:}";;
          error:*) LINE="error: ${RES#error:}";;
          *) LINE="error: no-result";;
        esac
      fi
    fi
    echo "$NAME ($RPATH): $LINE"
    [ -z "$WARNS" ] || printf '%s\n' "$WARNS" | sed 's/^/  /'
    case "$LINE" in
      created|"would create") N_CREATED=$((N_CREATED+1));;
      updated*|"would update"*|repaired*|"would repair"*) N_UPDATED=$((N_UPDATED+1));;
      unchanged*) N_UNCHANGED=$((N_UNCHANGED+1));;
      skipped*) N_SKIPPED=$((N_SKIPPED+1));;
      *) N_ERRORS=$((N_ERRORS+1));;
    esac
  done <<<"$LIST"
  echo "Summary: $N_CREATED created, $N_UPDATED updated, $N_UNCHANGED unchanged, $N_SKIPPED skipped, $N_ERRORS errors"
  [ "$DRY" = 0 ] || echo "Dry run: nothing was written."
  [ "$N_ERRORS" = 0 ] || exit 1
  exit 0
fi

COMMON="$(git rev-parse --git-common-dir 2>/dev/null)" || { [ "$ACTION" = check ] && exit 0; echo "ERROR: run this inside the project's repo." >&2; [ "$ACTION" = add ] && finish skipped:not-a-repo 1; exit 1; }
COMMON="$(cd "$COMMON" && pwd)"
[ "$(basename "$COMMON")" = .git ] || { [ "$ACTION" = check ] && exit 0; echo "ERROR: the repo's main checkout was not found ($COMMON)." >&2; [ "$ACTION" = add ] && finish skipped:not-main-checkout 1; exit 1; }
ROOT="$(dirname "$COMMON")"; EXCLUDE="$COMMON/info/exclude"; YAML="$ROOT/orca.yaml"; INCLUDE="$ROOT/.worktreeinclude"

tracked()     { git -C "$ROOT" ls-files --error-unmatch -- "$1" >/dev/null 2>&1; }
has_line()    { [ -f "$2" ] && grep -qxF "$1" "$2"; }
remove_line() { [ -f "$2" ] || return 0; local t; t="$(mktemp)"; grep -vxF "$1" "$2" > "$t" || true; cat "$t" > "$2"; rm -f "$t"; }
ours()        { [ -f "$YAML" ] && grep -qxF "$MARK" "$YAML"; }

# Would Orca run launch.sh from orca.yaml? Reads only the repo's hookSettings through the Orca CLI (best effort).
# Mirrors Orca's policy resolution (see research/roles-yaml-policy.md). Prints "<policy> <local launches the kit> <setupRunPolicy>".
IFS= read -r -d '' JQ_DEFS <<'EOF' || true
def trim: if type == "string" then sub("^\\s+"; "") | sub("\\s+$"; "") else "" end;
def runs_kit: split("\n") | map(select(test("^\\s*#") | not) | sub("\\s#.*$"; "") | [splits("[;&|]+")] | map(trim | select(test("^(echo|printf)(\\s|$)") | not)))
  | flatten | any(test("/[\"']?\\.orca-roles/bin/launch\\.sh[\"']?(\\s|$)"));
EOF
IFS= read -r -d '' POLICY_JQ <<'EOF' || true
(.result.repo.hookSettings // {}) as $h
| (($h.scripts // {}).setup | trim) as $local
| (if ($h.commandSourcePolicy | IN("local-only", "run-both", "shared-only")) then $h.commandSourcePolicy
   elif ($h | has("commandSourcePolicy") | not) and $local != "" then "local-only"
   else "shared-only" end) as $policy
| ($local | runs_kit) as $kit
| "\($policy) \($kit) \($h.setupRunPolicy // "run-by-default")"
EOF
# Sets POLICY_INFO on success, POLICY_WHY (reason) on failure.
lookup_policy() {
  local out id
  POLICY_INFO=""; POLICY_WHY=""
  command -v jq >/dev/null 2>&1 || { POLICY_WHY="jq not found"; return 1; }
  if [ -z "${ORCA_CLI_COMMAND:-}" ]; then type -P orca >/dev/null 2>&1 || { POLICY_WHY="Orca CLI not found"; return 1; }
  else type -P orca >/dev/null 2>&1 || command -v "$ORCA_CLI_COMMAND" >/dev/null 2>&1 || { POLICY_WHY="Orca CLI not found"; return 1; }; fi
  out="$(orca_cli repo show --repo "path:$ROOT" --json 2>/dev/null)" || true
  if ! jq -e '.result.repo | type == "object"' <<<"$out" >/dev/null 2>&1; then
    if [ "$(jq -r '.error.code // empty' <<<"$out" 2>/dev/null)" = runtime_unavailable ]; then POLICY_WHY="Orca is not running"; return 1; fi
    out="$(orca_cli worktree show --worktree current --json 2>/dev/null)" || true
    id="$(jq -r '.result.worktree.repoId // empty' <<<"$out" 2>/dev/null)" || true
    if [ -z "$id" ]; then
      [ "$(jq -r '.error.code // empty' <<<"$out" 2>/dev/null)" = runtime_unavailable ] && POLICY_WHY="Orca is not running" || POLICY_WHY="project not registered in Orca"
      return 1
    fi
    out="$(orca_cli repo show --repo "id:$id" --json 2>/dev/null)" || true
    jq -e '.result.repo | type == "object"' <<<"$out" >/dev/null 2>&1 || { POLICY_WHY="unexpected response from Orca"; return 1; }
  fi
  POLICY_INFO="$(jq -r "$JQ_DEFS $POLICY_JQ" <<<"$out" 2>/dev/null)" || true
  [ -n "$POLICY_INFO" ] || { POLICY_WHY="unexpected response from Orca"; return 1; }
}

warn_run_policy() {
  case "$1" in
    ask) echo "WARNING: this project's setup policy is 'ask': Orca asks each time, and 'orca worktree create' needs '--setup run'. The kit does not start by itself." >&2;;
    skip-by-default) echo "WARNING: this project's setup policy is 'skip-by-default': setup does not run automatically, so the kit will not start by itself." >&2;;
  esac
}

# Read-only: does a new worktree start the kit? Silent when Orca cannot be asked. Always exits 0.
if [ "$ACTION" = check ]; then
  lookup_policy || exit 0
  read -r POLICY LOCAL_KIT RUNPOL <<<"$POLICY_INFO"
  SHARED_KIT=false
  # Any non-comment line of orca.yaml counts, not only the setup script's (known limit)
  if [ -f "$YAML" ] && [ "$(jq -Rsr "$JQ_DEFS runs_kit" "$YAML" 2>/dev/null)" = true ] \
    && { tracked orca.yaml || { has_line orca.yaml "$INCLUDE" && git -C "$ROOT" check-ignore -q orca.yaml; }; }; then SHARED_KIT=true; fi
  case "$POLICY" in
    local-only) LAUNCHES="$LOCAL_KIT";;
    shared-only) LAUNCHES="$SHARED_KIT";;
    *) if [ "$LOCAL_KIT" = true ] || [ "$SHARED_KIT" = true ]; then LAUNCHES=true; else LAUNCHES=false; fi;;
  esac
  if [ "$LAUNCHES" != true ]; then
    case "$POLICY" in
      local-only) echo "WARNING: new worktrees of this project will not start the kit: Orca's setup source is local-only and the local setup script does not run launch.sh. Put \$HOME/.orca-roles/bin/launch.sh as the first line of that script (Settings → Repository → $(basename "$ROOT") → Setup script), or switch the setup source to \"run both\" and run roles-yaml." >&2;;
      shared-only) echo "WARNING: new worktrees of this project will not start the kit: Orca's setup source is shared-only and no orca.yaml that reaches new worktrees runs launch.sh. Run roles-yaml, or add \$HOME/.orca-roles/bin/launch.sh to the committed orca.yaml's setup script." >&2;;
      *) echo "WARNING: new worktrees of this project will not start the kit: neither the local setup script nor an orca.yaml that reaches new worktrees runs launch.sh. Run roles-yaml, or put \$HOME/.orca-roles/bin/launch.sh in the local setup script (Settings → Repository → $(basename "$ROOT") → Setup script)." >&2;;
    esac
    exit 0
  fi
  if [ "$POLICY" = run-both ] && [ "$LOCAL_KIT" = true ] && [ "$SHARED_KIT" = true ]; then
    echo "WARNING: new worktrees of this project start the kit twice: both the local setup script and orca.yaml run launch.sh. Fix it with roles-yaml --remove, or drop launch.sh from the local setup script." >&2
  fi
  warn_run_policy "$RUNPOL"
  exit 0
fi

if [ "$ACTION" = remove ]; then
  if ours; then rm -f "$YAML"; echo "Deleted $YAML"; fi
  if ! tracked .worktreeinclude; then
    remove_line orca.yaml "$INCLUDE"
    # If only our comment was left, the file was ours: it is deleted
    if [ -f "$INCLUDE" ] && ! grep -qvE "^(# Generated by orca-roles.*)?$" "$INCLUDE"; then rm -f "$INCLUDE"; echo "Deleted $INCLUDE"; remove_line .worktreeinclude "$EXCLUDE"; fi
  fi
  remove_line orca.yaml "$EXCLUDE"
  echo "Done: new worktrees of this project will no longer run the kit through orca.yaml."
  exit 0
fi

# Nothing committed is ever modified: that would leave pending changes in the project
if tracked orca.yaml; then
  echo "ERROR: this project already has a committed orca.yaml. Add to its 'scripts: setup:' the line" >&2
  echo "  $LAUNCH" >&2
  echo "or configure it in Settings → Repository → Setup script." >&2; finish skipped:committed-orca-yaml 1
fi
if [ -f "$YAML" ] && ! ours; then
  echo "ERROR: there is already an uncommitted orca.yaml the kit did not generate ($YAML); leaving it alone." >&2
  echo "Add to its 'scripts: setup:' the line $LAUNCH, or delete it and try again." >&2; finish skipped:foreign-orca-yaml 1
fi
if tracked .worktreeinclude && ! has_line orca.yaml "$INCLUDE"; then
  echo "ERROR: this project has a committed .worktreeinclude without 'orca.yaml'. Add that line (and commit it)," >&2
  echo "or configure the setup script in Settings → Repository → Setup script." >&2; finish skipped:committed-worktreeinclude 1
fi

# Does Orca run orca.yaml at all? Only checked when adding; nothing is written if it would not help.
CHECKED=0
if lookup_policy; then
  CHECKED=1; read -r POLICY LOCAL_KIT RUNPOL <<<"$POLICY_INFO"
  warn_run_policy "$RUNPOL"
  if [ "$POLICY" = local-only ] && [ "$LOCAL_KIT" != true ]; then
    echo "ERROR: this project's setup source is local-only (set explicitly, or implied: no source was chosen and Settings has a script): Orca ignores orca.yaml, so roles-yaml would do nothing. Nothing was written." >&2
    echo "Either:" >&2
    echo "  1. put \$HOME/.orca-roles/bin/launch.sh as the FIRST line of the local setup script (Settings → Repository → $(basename "$ROOT") → Setup script), or" >&2
    echo "  2. switch the setup source to \"run both\" in that same place, so orca.yaml runs next to the local script." >&2
    echo "With no source chosen, any script in the local box makes it local-only." >&2; finish skipped:local-only-policy 1
  fi
  if [ "$LOCAL_KIT" = true ] && { [ "$POLICY" = local-only ] || [ "$POLICY" = run-both ]; }; then
    echo "roles-yaml is not needed: the project's local setup script already runs launch.sh."
    if [ "$POLICY" = run-both ] && ours; then
      echo "With \"run both\" and the orca.yaml roles-yaml created earlier, the kit is running TWICE in new worktrees now. Fix it with: roles-yaml --remove (or drop launch.sh from the local setup script). Nothing was written."
    else
      echo "Nothing was written."
      [ "$POLICY" = run-both ] && echo "With \"run both\", orca.yaml would make the kit run twice."
    fi
    finish skipped:local-script 0
  fi
else
  echo "Note: could not check Orca's setup policy ($POLICY_WHY)."
fi

MODE_TXT="in mode $MODE"; [ -n "$MODE" ] || MODE_TXT="in the default mode"
gen_yaml() {
  printf '%s\n' "$MARK"
  echo "# Local: ignored in .git/info/exclude and copied to every new worktree by .worktreeinclude. To remove it: roles-yaml --remove"
  echo "scripts:"
  echo "  setup: |"
  printf '    %s\n' "$LAUNCH"
}
if [ "$DRY" = 1 ]; then
  if ! ours; then echo "Would create $YAML (dry run: nothing was written)"; finish created 0
  elif [ "$(gen_yaml)" != "$(cat "$YAML")" ]; then echo "Would update $YAML: new worktrees would start $MODE_TXT (dry run: nothing was written)"; finish updated 0
  else echo "Nothing would change: $YAML already starts new worktrees $MODE_TXT (dry run)."; finish unchanged 0; fi
fi
WROTE=0; RESULT=unchanged
if ! ours; then
  gen_yaml > "$YAML"; WROTE=1; RESULT=created
  echo "Created $YAML"
elif [ "$(gen_yaml)" != "$(cat "$YAML")" ]; then
  gen_yaml > "$YAML"; WROTE=1; RESULT=updated
  echo "Updated $YAML: new worktrees start $MODE_TXT"
else
  echo "Nothing changed: $YAML already starts new worktrees $MODE_TXT."
fi
mkdir -p "$COMMON/info"; touch "$EXCLUDE"
has_line orca.yaml "$EXCLUDE" || echo orca.yaml >> "$EXCLUDE"
if ! tracked .worktreeinclude; then
  [ -f "$INCLUDE" ] || echo "# Generated by orca-roles: ignored files Orca copies to every new worktree" > "$INCLUDE"
  has_line orca.yaml "$INCLUDE" || echo orca.yaml >> "$INCLUDE"
  has_line .worktreeinclude "$EXCLUDE" || echo .worktreeinclude >> "$EXCLUDE"
fi

# Check: Orca only copies what git considers ignored
git -C "$ROOT" check-ignore -q orca.yaml || { echo "ERROR: git does not consider orca.yaml ignored; Orca would not copy it." >&2; finish error:not-ignored 1; }
echo "Done: new worktrees of $(basename "$ROOT") will run the kit. There is nothing to commit."
if [ "$WROTE" = 1 ]; then
  if [ -n "$MODE" ]; then echo "New worktrees of this project start in mode $MODE"
  else echo "New worktrees of this project start in the default mode (settings.mode, or .orca-roles.json if the project has one)"; fi
  echo "Existing worktrees keep their mode: use roles --mode <mode> in them."
fi
[ "$CHECKED" = 1 ] || echo "Note: what runs depends on the project's setup source (Settings → Repository): local-only uses only the Settings script and ignores orca.yaml, run-both runs both, shared-only runs only orca.yaml."
finish "$RESULT" 0
