#!/usr/bin/env bash
# Registers the kit as a project's setup script without committing anything (the roles-yaml command).
# Creates orca.yaml at the main checkout's root, ignores it in .git/info/exclude (local, .gitignore is not touched) and lists it
# in .worktreeinclude, also ignored: Orca copies the ignored files listed there to every new worktree,
# before looking for its setup script, so orca.yaml reaches the worktree and Orca runs launch.sh.
# Usage (from any folder in the project):  roles-yaml   |   roles-yaml --remove
set -euo pipefail
MARK="# Generated by orca-roles (roles-yaml)"
case "${1:-}" in -h|--help) sed -n 2,6p "$0"; exit 0;; ""|--remove) ;; *) echo "Unknown option: $1" >&2; exit 1;; esac

COMMON="$(git rev-parse --git-common-dir 2>/dev/null)" || { echo "ERROR: run this inside the project's repo." >&2; exit 1; }
COMMON="$(cd "$COMMON" && pwd)"
[ "$(basename "$COMMON")" = .git ] || { echo "ERROR: the repo's main checkout was not found ($COMMON)." >&2; exit 1; }
ROOT="$(dirname "$COMMON")"; EXCLUDE="$COMMON/info/exclude"; YAML="$ROOT/orca.yaml"; INCLUDE="$ROOT/.worktreeinclude"

tracked()     { git -C "$ROOT" ls-files --error-unmatch -- "$1" >/dev/null 2>&1; }
has_line()    { [ -f "$2" ] && grep -qxF "$1" "$2"; }
remove_line() { [ -f "$2" ] || return 0; local t; t="$(mktemp)"; grep -vxF "$1" "$2" > "$t" || true; cat "$t" > "$2"; rm -f "$t"; }
ours()        { [ -f "$YAML" ] && grep -qxF "$MARK" "$YAML"; }

if [ "${1:-}" = --remove ]; then
  if ours; then rm -f "$YAML"; echo "Deleted $YAML"; fi
  if ! tracked .worktreeinclude; then
    remove_line orca.yaml "$INCLUDE"
    # If only our comment was left, the file was ours: it is deleted
    if [ -f "$INCLUDE" ] && ! grep -qvE "^(# Generated by orca-roles.*)?$" "$INCLUDE"; then rm -f "$INCLUDE"; echo "Deleted $INCLUDE"; remove_line .worktreeinclude "$EXCLUDE"; fi
  fi
  remove_line orca.yaml "$EXCLUDE"
  echo "Done: new worktrees of this project will no longer run the kit through orca.yaml."
  exit 0
fi

# Nothing committed is ever modified: that would leave pending changes in the project
if tracked orca.yaml; then
  echo "ERROR: this project already has a committed orca.yaml. Add to its 'scripts: setup:' the line" >&2
  echo "  \$HOME/.orca-roles/bin/launch.sh" >&2
  echo "or configure it in Settings → Repository → Setup script." >&2; exit 1
fi
if [ -f "$YAML" ] && ! ours; then
  echo "ERROR: there is already an uncommitted orca.yaml the kit did not generate ($YAML); leaving it alone." >&2
  echo "Add to its 'scripts: setup:' the line \$HOME/.orca-roles/bin/launch.sh, or delete it and try again." >&2; exit 1
fi
if tracked .worktreeinclude && ! has_line orca.yaml "$INCLUDE"; then
  echo "ERROR: this project has a committed .worktreeinclude without 'orca.yaml'. Add that line (and commit it)," >&2
  echo "or configure the setup script in Settings → Repository → Setup script." >&2; exit 1
fi

if ! ours; then
  cat > "$YAML" <<EOF
$MARK
# Local: ignored in .git/info/exclude and copied to every new worktree by .worktreeinclude. To remove it: roles-yaml --remove
scripts:
  setup: |
    \$HOME/.orca-roles/bin/launch.sh
EOF
  echo "Created $YAML"
fi
mkdir -p "$COMMON/info"; touch "$EXCLUDE"
has_line orca.yaml "$EXCLUDE" || echo orca.yaml >> "$EXCLUDE"
if ! tracked .worktreeinclude; then
  [ -f "$INCLUDE" ] || echo "# Generated by orca-roles: ignored files Orca copies to every new worktree" > "$INCLUDE"
  has_line orca.yaml "$INCLUDE" || echo orca.yaml >> "$INCLUDE"
  has_line .worktreeinclude "$EXCLUDE" || echo .worktreeinclude >> "$EXCLUDE"
fi

# Check: Orca only copies what git considers ignored
git -C "$ROOT" check-ignore -q orca.yaml || { echo "ERROR: git does not consider orca.yaml ignored; Orca would not copy it." >&2; exit 1; }
echo "Done: new worktrees of $(basename "$ROOT") will run the kit. There is nothing to commit."
echo "Note: if this project already has its own setup script in Settings → Repository, Orca uses that one and ignores orca.yaml."
